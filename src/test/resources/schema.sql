CREATE TABLE users (
    id BINARY(16) PRIMARY KEY,
    nickname VARCHAR(16),
    avatar_url VARCHAR(1024),
    onboarding_completed_at TIMESTAMP(6),
    deletion_requested_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    deleted_at TIMESTAMP(6)
);

CREATE TABLE venues (
    id BINARY(16) PRIMARY KEY,
    owner_id BINARY(16) NOT NULL,
    name VARCHAR(255) NOT NULL,
    address VARCHAR(1000),
    corner_a_latitude DOUBLE,
    corner_a_longitude DOUBLE,
    corner_b_latitude DOUBLE,
    corner_b_longitude DOUBLE,
    corner_c_latitude DOUBLE,
    corner_c_longitude DOUBLE,
    corner_d_latitude DOUBLE,
    corner_d_longitude DOUBLE,
    raw_corner_a_latitude DOUBLE,
    raw_corner_a_longitude DOUBLE,
    raw_corner_b_latitude DOUBLE,
    raw_corner_b_longitude DOUBLE,
    raw_corner_c_latitude DOUBLE,
    raw_corner_c_longitude DOUBLE,
    raw_corner_d_latitude DOUBLE,
    raw_corner_d_longitude DOUBLE,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_venue_user FOREIGN KEY (owner_id) REFERENCES users(id)
);

CREATE TABLE matches (
    id BINARY(16) PRIMARY KEY,
    owner_id BINARY(16) NOT NULL,
    venue_id BINARY(16),
    title VARCHAR(255),
    venue_name_snapshot VARCHAR(255),
    venue_address_snapshot VARCHAR(1000),
    scheduled_at TIMESTAMP(6),
    status VARCHAR(32) NOT NULL,
    started_at TIMESTAMP(6),
    ended_at TIMESTAMP(6),
    version BIGINT NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_match_user FOREIGN KEY (owner_id) REFERENCES users(id),
    CONSTRAINT fk_match_venue FOREIGN KEY (venue_id) REFERENCES venues(id) ON DELETE SET NULL
);

CREATE TABLE quarters (
    id BINARY(16) PRIMARY KEY,
    match_id BINARY(16) NOT NULL,
    number INT NOT NULL,
    duration_seconds INT NOT NULL,
    status VARCHAR(32) NOT NULL,
    started_at TIMESTAMP(6),
    ended_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_quarter_number UNIQUE (match_id, number),
    CONSTRAINT fk_quarter_match FOREIGN KEY (match_id) REFERENCES matches(id)
);

CREATE TABLE quarter_player_stats (
    quarter_id BINARY(16) PRIMARY KEY,
    goals INT NOT NULL,
    assists INT NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    FOREIGN KEY (quarter_id) REFERENCES quarters(id)
);

CREATE TABLE quarter_positions (
    quarter_id BINARY(16) PRIMARY KEY,
    position_code VARCHAR(32) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    FOREIGN KEY (quarter_id) REFERENCES quarters(id)
);

CREATE TABLE workout_payloads (
    id BINARY(16) PRIMARY KEY,
    quarter_id BINARY(16) NOT NULL,
    user_id BINARY(16) NOT NULL,
    start_date TIMESTAMP(6) NOT NULL,
    end_date TIMESTAMP(6) NOT NULL,
    total_calories DOUBLE NOT NULL,
    total_distance DOUBLE NOT NULL,
    events_json VARCHAR(1000000),
    field_snapshot VARCHAR(1000000),
    CONSTRAINT uk_workout_quarter UNIQUE (quarter_id),
    CONSTRAINT uk_workout_quarter_id UNIQUE (quarter_id, id),
    FOREIGN KEY (quarter_id) REFERENCES quarters(id),
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE track_points (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_payload_id BINARY(16) NOT NULL,
    sample_seq INT NOT NULL,
    latitude DOUBLE NOT NULL,
    longitude DOUBLE NOT NULL,
    altitude DOUBLE NOT NULL,
    horizontal_accuracy DOUBLE NOT NULL,
    speed DOUBLE NOT NULL,
    course DOUBLE NOT NULL,
    timestamp TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_track_payload_seq UNIQUE (workout_payload_id, sample_seq),
    FOREIGN KEY (workout_payload_id) REFERENCES workout_payloads(id)
);

CREATE TABLE heart_rate_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_payload_id BINARY(16) NOT NULL,
    sample_seq INT NOT NULL,
    timestamp TIMESTAMP(6) NOT NULL,
    bpm DOUBLE NOT NULL,
    CONSTRAINT uk_heart_payload_seq UNIQUE (workout_payload_id, sample_seq),
    FOREIGN KEY (workout_payload_id) REFERENCES workout_payloads(id)
);

CREATE TABLE quarter_summaries (
    quarter_id BINARY(16) PRIMARY KEY,
    workout_payload_id BINARY(16) NOT NULL,
    calculation_job_id BINARY(16) NOT NULL,
    calculation_status VARCHAR(32) NOT NULL,
    calculation_version VARCHAR(64) NOT NULL,
    calculation_parameters VARCHAR(4000) NOT NULL,
    metric_status VARCHAR(4000) NOT NULL,
    source_payload_hash VARCHAR(64) NOT NULL,
    duration_seconds DOUBLE,
    max_speed_mps DOUBLE,
    total_distance_m DOUBLE,
    total_calories_kcal DOUBLE,
    average_speed_mps DOUBLE,
    high_intensity_distance_m DOUBLE,
    acceleration_count INT,
    deceleration_count INT,
    direction_change_count INT,
    average_heart_rate_bpm DOUBLE,
    max_heart_rate_bpm DOUBLE,
    trimp_edwards DOUBLE,
    hr_max_reference_bpm DOUBLE,
    valid_hr_duration_seconds DOUBLE,
    valid_gps_duration_seconds DOUBLE,
    calculated_at TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL,
    FOREIGN KEY (quarter_id) REFERENCES quarters(id),
    FOREIGN KEY (quarter_id, workout_payload_id)
        REFERENCES workout_payloads(quarter_id, id)
);

CREATE TABLE auth_identities (
    id BINARY(16) PRIMARY KEY,
    user_id BINARY(16) NOT NULL,
    provider VARCHAR(64) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_identity_provider_subject UNIQUE (provider, subject),
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE email_credentials (
    user_id BINARY(16) PRIMARY KEY,
    email VARCHAR(320) NOT NULL,
    normalized_email VARCHAR(320) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    email_verified_at TIMESTAMP(6) NOT NULL,
    password_changed_at TIMESTAMP(6) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_email_credentials_normalized UNIQUE (normalized_email),
    FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE email_verification_flows (
    id BINARY(16) PRIMARY KEY,
    normalized_email VARCHAR(320) NOT NULL,
    purpose VARCHAR(32) NOT NULL,
    code_hash CHAR(64),
    failed_attempts INT NOT NULL,
    code_expires_at TIMESTAMP(6) NOT NULL,
    last_sent_at TIMESTAMP(6) NOT NULL,
    verified_at TIMESTAMP(6),
    invalidated_at TIMESTAMP(6),
    action_token_hash CHAR(64),
    action_token_expires_at TIMESTAMP(6),
    action_token_consumed_at TIMESTAMP(6),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_email_flow_action_token UNIQUE (action_token_hash),
    CONSTRAINT ck_email_flow_failed_attempts
        CHECK (failed_attempts BETWEEN 0 AND 5),
    CONSTRAINT ck_email_flow_action_token_state CHECK (
        (action_token_hash IS NULL AND action_token_expires_at IS NULL)
        OR (action_token_hash IS NOT NULL AND action_token_expires_at IS NOT NULL
            AND verified_at IS NOT NULL)
    )
);
CREATE INDEX idx_email_flow_latest
    ON email_verification_flows(normalized_email, purpose, created_at);
CREATE INDEX idx_email_flow_code_expiry
    ON email_verification_flows(code_expires_at);
CREATE INDEX idx_email_flow_action_expiry
    ON email_verification_flows(action_token_expires_at);

CREATE TABLE auth_rate_limit_keys (
    rate_action VARCHAR(64) NOT NULL,
    limit_type VARCHAR(16) NOT NULL,
    key_value VARCHAR(320) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (rate_action, limit_type, key_value)
);

CREATE TABLE auth_rate_limit_events (
    id BINARY(16) PRIMARY KEY,
    rate_action VARCHAR(64) NOT NULL,
    limit_type VARCHAR(16) NOT NULL,
    key_value VARCHAR(320) NOT NULL,
    occurred_at TIMESTAMP(6) NOT NULL,
    FOREIGN KEY (rate_action, limit_type, key_value)
        REFERENCES auth_rate_limit_keys(rate_action, limit_type, key_value)
);
CREATE INDEX idx_auth_rate_limit_window
    ON auth_rate_limit_events(rate_action, limit_type, key_value, occurred_at);

